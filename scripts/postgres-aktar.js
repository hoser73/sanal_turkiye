#!/usr/bin/env node
// PostgreSQL + PostGIS geçişi (plan §13.3). SQLite şemasından PostgreSQL DDL'i üretir, verileri CSV olarak dışa aktarır,
// parsel geometrilerini (ızgara hücresi poligonu, EPSG:4326) WKT olarak ekler ve psql ile çalıştırılacak yükleme betiğini yazar.
//   npm run postgres-aktar -- --sema               → db/postgres/sema.sql
//   npm run postgres-aktar -- --disa-aktar <dizin>  → <dizin>/*.csv + yukle.sql  (psql "$DATABASE_URL" -f <dizin>/yukle.sql)
// Not: Uygulama katmanı hâlâ senkron better-sqlite3 kullanır; Postgres'e geçişte veri erişimi zaman uyumsuz sürücüye (pg)
// taşınmalıdır (docs/postgres-gecisi.md). Bu betik veriyi ve şemayı hazırlar; Postgres'e karşı burada test edilmemiştir.
const fs = require('fs');
const path = require('path');
const db = require('../server/db');
const I = require('../server/harita/izgara');

const tablolar = () => db.prepare(`SELECT name, sql FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name`).all();
const kimlik = (ad) => `"${ad}"`;

function tip(sqliteTip, pk) {
  const t = String(sqliteTip || '').toUpperCase();
  if (t.includes('INT')) return pk ? 'BIGINT' : 'BIGINT';
  if (t.includes('REAL') || t.includes('FLOA') || t.includes('DOUB')) return 'DOUBLE PRECISION';
  return 'TEXT';
}
function varsayilan(v) {
  if (v == null) return '';
  if (/datetime\('now'\)/i.test(v)) return ` DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')`;
  return ` DEFAULT ${v.replace(/^\((.*)\)$/, '$1')}`;
}

function sema() {
  const satirlar = ['-- Sanal Türkiye — PostgreSQL + PostGIS şeması (scripts/postgres-aktar.js ile SQLite şemasından üretildi)',
    'CREATE EXTENSION IF NOT EXISTS postgis;', 'BEGIN;'];
  const sonraki = [];
  for (const { name } of tablolar()) {
    const kolonlar = db.prepare(`PRAGMA table_info(${kimlik(name)})`).all();
    const pk = kolonlar.filter((k) => k.pk).sort((a, b) => a.pk - b.pk);
    const tekIntPk = pk.length === 1 && /INT/i.test(pk[0].type);
    const yabanci = db.prepare(`PRAGMA foreign_key_list(${kimlik(name)})`).all();
    const tanimlar = kolonlar.map((k) => {
      const kimlikKolonu = tekIntPk && k.pk ? ' GENERATED BY DEFAULT AS IDENTITY' : '';
      return `  ${kimlik(k.name)} ${tip(k.type, k.pk)}${kimlikKolonu}${k.notnull && !k.pk ? ' NOT NULL' : ''}${kimlikKolonu ? '' : varsayilan(k.dflt_value)}`;
    });
    if (pk.length) tanimlar.push(`  PRIMARY KEY (${pk.map((k) => kimlik(k.name)).join(', ')})`);
    // UNIQUE kısıtları (kolon düzeyi ve tablo düzeyi): SQLite bunları origin='u' otomatik indeks olarak tutar
    for (const ix of db.prepare(`PRAGMA index_list(${kimlik(name)})`).all().filter((x) => x.origin === 'u')) {
      const kol = db.prepare(`PRAGMA index_info(${kimlik(ix.name)})`).all().sort((a, b) => a.seqno - b.seqno).map((c) => kimlik(c.name));
      tanimlar.push(`  UNIQUE (${kol.join(', ')})`);
    }
    if (name === 'parcels') tanimlar.push('  "geom" geometry(Polygon, 4326)', '  "merkez" geometry(Point, 4326)');
    if (name === 'regions') tanimlar.push('  "merkez" geometry(Point, 4326)');
    satirlar.push(`CREATE TABLE IF NOT EXISTS ${kimlik(name)} (\n${tanimlar.join(',\n')}\n);`);
    for (const f of yabanci) sonraki.push(`ALTER TABLE ${kimlik(name)} ADD FOREIGN KEY (${kimlik(f.from)}) REFERENCES ${kimlik(f.table)}(${kimlik(f.to)})${f.on_delete !== 'NO ACTION' ? ` ON DELETE ${f.on_delete}` : ''} NOT VALID;`);
  }
  // İndeksler (kısmi indeksler dahil; SQLite sözdizimi büyük ölçüde uyumludur)
  for (const ix of db.prepare(`SELECT sql FROM sqlite_master WHERE type = 'index' AND sql IS NOT NULL`).all()) {
    sonraki.push(ix.sql.replace(/\bIF NOT EXISTS\b/i, 'IF NOT EXISTS') + ';');
  }
  sonraki.push(
    'CREATE INDEX IF NOT EXISTS ix_parcels_geom ON parcels USING GIST (geom);',
    'CREATE INDEX IF NOT EXISTS ix_parcels_merkez ON parcels USING GIST (merkez);',
    'CREATE INDEX IF NOT EXISTS ix_regions_merkez ON regions USING GIST (merkez);',
    '-- Denetim kaydı değiştirilemez',
    `CREATE OR REPLACE FUNCTION audit_degismez() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'audit_events değiştirilemez'; END $$;`,
    'DROP TRIGGER IF EXISTS audit_no_update ON audit_events;',
    'CREATE TRIGGER audit_no_update BEFORE UPDATE OR DELETE ON audit_events FOR EACH ROW EXECUTE FUNCTION audit_degismez();',
    '-- Defter bütünlüğü: her işlem grubu dengeli olmalı (raporlama görünümü)',
    `CREATE OR REPLACE VIEW defter_dengesiz AS SELECT tx_group, round(sum(debit) - sum(credit), 2) AS fark FROM wallet_ledger GROUP BY tx_group HAVING round(sum(debit) - sum(credit), 2) <> 0;`,
  );
  return [...satirlar, ...sonraki, 'COMMIT;'].join('\n') + '\n';
}

// CSV: RFC 4180 (tırnak içinde, çift tırnak kaçışlı); NULL boş alan
const csvAlan = (v) => (v == null ? '' : `"${String(v).replace(/"/g, '""')}"`);
function disaAktar(dizin) {
  fs.mkdirSync(dizin, { recursive: true });
  const yukle = ['\\set ON_ERROR_STOP on', `\\i ${path.resolve(dizin, 'sema.sql')}`, 'BEGIN;'];
  fs.writeFileSync(path.join(dizin, 'sema.sql'), sema());
  const ozet = {};
  for (const { name } of tablolar()) {
    const kolonlar = db.prepare(`PRAGMA table_info(${kimlik(name)})`).all().map((k) => k.name);
    const dosya = path.join(dizin, `${name}.csv`);
    const akis = fs.openSync(dosya, 'w');
    let n = 0;
    for (const s of db.prepare(`SELECT * FROM ${kimlik(name)}`).iterate()) {
      fs.writeSync(akis, kolonlar.map((k) => csvAlan(s[k])).join(',') + '\n');
      n++;
    }
    fs.closeSync(akis);
    ozet[name] = n;
    yukle.push(`\\copy ${kimlik(name)} (${kolonlar.map(kimlik).join(', ')}) FROM '${path.resolve(dosya)}' WITH (FORMAT csv)`);
  }
  // Parsel geometrileri: ızgara hücresinin gerçek poligonu
  const geo = fs.openSync(path.join(dizin, 'parcels_geom.csv'), 'w');
  for (const p of db.prepare(`SELECT id, grid_x, grid_y, centroid_lon, centroid_lat FROM parcels`).iterate()) {
    const halka = I.hucrePoligonu(p.grid_x, p.grid_y).coordinates[0].map(([x, y]) => `${x} ${y}`).join(', ');
    fs.writeSync(geo, `${csvAlan(p.id)},${csvAlan(`POLYGON((${halka}))`)},${csvAlan(`POINT(${p.centroid_lon} ${p.centroid_lat})`)}\n`);
  }
  fs.closeSync(geo);
  yukle.push(
    'CREATE TEMP TABLE parsel_geo (id TEXT, poligon TEXT, nokta TEXT);',
    `\\copy parsel_geo FROM '${path.resolve(dizin, 'parcels_geom.csv')}' WITH (FORMAT csv)`,
    'UPDATE parcels p SET geom = ST_GeomFromText(g.poligon, 4326), merkez = ST_GeomFromText(g.nokta, 4326) FROM parsel_geo g WHERE g.id = p.id;',
    'UPDATE regions SET merkez = ST_SetSRID(ST_MakePoint(center_lon, center_lat), 4326) WHERE center_lon IS NOT NULL;',
    // Kimlik dizilerini en büyük değere taşı
    ...tablolar().filter(({ name }) => { const pk = db.prepare(`PRAGMA table_info(${kimlik(name)})`).all().filter((k) => k.pk); return pk.length === 1 && /INT/i.test(pk[0].type); })
      .map(({ name }) => { const pk = db.prepare(`PRAGMA table_info(${kimlik(name)})`).all().find((k) => k.pk).name;
        return `SELECT setval(pg_get_serial_sequence('${kimlik(name)}', '${pk}'), COALESCE((SELECT MAX(${kimlik(pk)}) FROM ${kimlik(name)}), 0) + 1, false);`; }),
    'COMMIT;',
    'ANALYZE;',
  );
  // Yabancı anahtarlar NOT VALID eklenir (yükleme sırasından bağımsız); gerekirse sonradan ALTER TABLE … VALIDATE CONSTRAINT ile doğrulanır
  fs.writeFileSync(path.join(dizin, 'yukle.sql'), yukle.join('\n') + '\n');
  return ozet;
}

if (require.main === module) {
  if (process.argv.includes('--sema')) {
    const hedef = path.join(__dirname, '..', 'db', 'postgres', 'sema.sql');
    fs.mkdirSync(path.dirname(hedef), { recursive: true });
    fs.writeFileSync(hedef, sema());
    console.log(`Şema yazıldı: ${hedef}`);
  } else {
    const i = process.argv.indexOf('--disa-aktar');
    if (i < 0) { console.error('Kullanım: --sema | --disa-aktar <dizin>'); process.exit(1); }
    const ozet = disaAktar(path.resolve(process.argv[i + 1] || 'data/postgres-aktarim'));
    console.log(JSON.stringify({ tamam: true, satirlar: ozet }, null, 1));
  }
}
module.exports = { sema, disaAktar };
